class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("techstore_lang") || "az";
    this.currencySymbol = "₼";
  }

  getLang() {
    return this.currentLang;
  }

  setLang(lang) {
    if (lang !== "az" && lang !== "en") return;
    this.currentLang = lang;
    localStorage.setItem("techstore_lang", lang);
    this.applyTranslations();
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
  }

  t(key) {
    return (TRANSLATIONS[this.currentLang] && TRANSLATIONS[this.currentLang][key]) || key;
  }

  formatPrice(amount) {
    const num = parseFloat(amount || 0);
    // Format: 1 999,00 ₼
    const formatted = num.toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, " ").replace(".", ",");
    return `${formatted} ${this.currencySymbol}`;
  }

  applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = this.t(key);
      if (translation) el.placeholder = translation;
    });

    // Update active state in UI language selectors
    document.querySelectorAll(".lang-btn").forEach(btn => {
      const lang = btn.getAttribute("data-lang");
      if (lang === this.currentLang) {
        btn.classList.add("active");
      } else {
        btn.classList.remove("active");
      }
    });

    document.documentElement.lang = this.currentLang;
  }
}

// Global i18n instance
window.i18n = new I18nManager();

document.addEventListener("DOMContentLoaded", () => {
  window.i18n.applyTranslations();
});
